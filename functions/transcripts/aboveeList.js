// Abovee 預約列表的抄字格式（ADR-0099）。
//
// 那是公司系統的**列表**，一頁 10 筆、二十幾欄塞不進一個畫面，所以她常拍左右兩張：
//   左半：預約狀態、預約日期、預約時段、姓名、病歷號、身份別、性別、電話、課程…預約來源
//   右半：預約來源、診間、交通方式…服務資源…取消原因…建立日期
// **右半邊沒有姓名、日期、時段** —— 兩張照「第幾列」對起來是 domain 的事（`domain/aboveeImport.js`）。
//
// **只抄十欄**。照片上沒有的那一欄就不出現在 `columns`，所以 domain 看得出這一張是哪一半。
// 電話、身份別、性別、操作人員、健管師、推薦人、建立者一律不抄。
//
// 「合併扣課」是 2026-10-05 加的（abovee-and-master/09）：兩列半小時合起來扣一次 60 分，
// 不抄那一欄的話 app 會記成兩段、扣兩次。
//
// 2026-10-08（prelaunch-fixes/13）提示詞多一條「被切掉一半的欄不要抄」：「診間」剛好在左右兩半的交界，
// 10/5 考試時左半張那一格被照抄成「治療」。**格式一格都沒變**（只加一句話）；domain 那一側另外改成
// 兩邊都有字時取比較長的（`aboveeImport.js` 的 `fullerCell()`），所以 Function 還沒重新部署也不會再蓋掉。
// 改了提示詞要重考（`scripts/ai-exam.mjs`）—— 併在同一輪的 issue 22。
//
// `dateFromText`／`dateToText` 是 2026-10-06 加的（course-form-and-sheet-2026-10-06/09，ADR-0129）：
// 畫面上方篩選列「預約日期(起)／(訖)」那兩格，照抄成字串。domain 拿來算「這次照片看得到哪一段時間」，
// 對 app 上有、照片上沒有的那幾段。不是表格的欄，所以不在 `ABOVEE_COLUMNS` 裡。

export const ABOVEE_COLUMNS = Object.freeze([
  '預約狀態', '預約日期', '預約時段', '姓名', '病歷號', '課程', '合併扣課', '診間', '服務資源', '取消原因',
]);

export const aboveeList = {
  schema: {
    type: 'object',
    properties: {
      columns: {
        type: 'array',
        items: { type: 'string', enum: [...ABOVEE_COLUMNS] },
        description: `照片上**看得到欄位名稱**的那幾欄，只從這十個裡挑，照照片由左到右的順序：${ABOVEE_COLUMNS.join('、')}`,
      },
      rows: {
        type: 'array',
        description: '表格的每一列，由上到下。每一列是一個字串陣列，跟 columns 同樣的順序、同樣的長度；那一格空白就寫空字串',
        items: { type: 'array', items: { type: 'string' } },
      },
      pageText: {
        type: 'string',
        description: '表格底下「N 筆・第 x/y 頁」那一句，照寫；看不到就不要這一格',
      },
      dateFromText: {
        type: 'string',
        description: '畫面上方「預約日期(起)」那一格裡的字，照寫（例：「2026/10/01」）；看不到就不要這一格',
      },
      dateToText: {
        type: 'string',
        description: '畫面上方「預約日期(訖)」那一格裡的字，照寫；看不到就不要這一格',
      },
    },
    required: ['columns', 'rows'],
  },

  prompt: `這是一張電腦螢幕上預約系統列表的照片（可能是整個表格的左半或右半）。
你的工作只有一件：**把表格裡的字照抄下來**，填進指定的格式。

規矩：
1. **只抄這十欄**：${ABOVEE_COLUMNS.join('、')}。照片上看得到的才放進 columns，順序照照片由左到右。
2. 其他欄一個字都不要抄，**尤其是電話**。
3. rows 每一列跟 columns 一樣長、一樣的順序。那一格空白就寫空字串，看不清楚也寫空字串並在 unreadable 講。
4. 照抄，不翻譯、不換算、不猜。病歷號前面的 0 要留著（「00001234」就寫「00001234」）。
   時段照寫（「09:00 - 10:15」）。預約狀態照畫面上的字寫（例：「確認前往」「課程完成」「已取消」）。
   「合併扣課」那一格照畫面寫（例：「是」）；畫的是勾勾就寫「是」，空白就寫空字串。
5. 表格上方有「預約日期(起)」「預約日期(訖)」兩格的話，那兩格裡的字照抄進 dateFromText、dateToText（不換算）；
   照片上看不到就不要那兩格。
6. 不是預約列表、或整張看不清楚時，readable 寫 false，其他都留空。
7. 照片邊緣**被切掉、只看得到一半的那一欄整欄不要抄**（不放進 columns）—— 抄半個字比不抄糟，
   那一欄在另一半的照片上是完整的。

例：一列是 確認前往｜2026-09-10｜09:00 - 10:15｜王小明｜00001234｜…｜SIS 60
→ columns ["預約狀態","預約日期","預約時段","姓名","病歷號","課程"]、
  rows [["確認前往","2026-09-10","09:00 - 10:15","王小明","00001234","SIS 60"]]。`,
};
