// 健檢做的比買的多：多出來那一次也追報告；補了二返額度之後那一串重算（ADR-0159，before-golive-2026-10-19/02）。
//
// 她：「5. 健檢做的次數比買的多，多出來那一次不會長報告那一串待辦。 好 修」。
// 問她「沒有二返額度的那一次，『約二返』先不長，等你補了額度才長？」—— 「是」。
//
// 以前「追蹤健檢報告」的名額被二返額度的總次數蓋住（ADR-0139 的技術選擇）：買 1 次、做了 2 次 → 第二次一張都不長，
// 「寄報告給醫師」也就等不到。現在每一次做完、二返還沒做完的健檢都追報告；「約二返」照舊受 `owed()` 管（沒有額度不長）。
//
// 拿掉那一層之後最重的副作用：切換那天匯進來、健檢做的比二返額度多的舊健檢，第一次存這位客人時會長一出生就逾期的報告。
// **超出二返額度的那一次、是匯進來的、從來沒有過任何一張鏈上待辦 → 不長**（ADR-0142 同一個判斷）。

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

import {
  syncFollowupTasks, FOLLOWUP_TASK_KIND, REPORT_TASK_KIND, SEND_REPORT_TASK_KIND,
} from '../public/js/domain/followups.js';
import { chainPlanLines, chainCountLines } from '../public/js/domain/consequences.js';
import { fromRoot } from './helpers/paths.js';

const COURSES = {
  'course-checkup': { id: 'course-checkup', name: '健檢', category: 'B', followupCourseId: 'course-followup' },
  'course-followup': { id: 'course-followup', name: '二返', category: 'A' },
};
const CUSTOMER = { id: 'c1', name: '客戶甲' };

const checkup = (over = {}) => ({
  id: 'ent-checkup', type: 'single', label: '健檢', courseId: 'course-checkup', totalQty: 1, ...over,
});
const followup = (over = {}) => ({
  id: 'ent-followup', type: 'single', label: '二返（健檢）', courseId: 'course-followup',
  totalQty: 1, followupForEntitlementId: 'ent-checkup', ...over,
});
const exam = (id, date, over = {}) => ({
  id, customerId: 'c1', customerName: '客戶甲', date, status: 'done',
  slots: [{ entitlementId: 'ent-checkup', courseId: 'course-checkup', status: 'done' }], ...over,
});
const second = (id, date, status = 'done', examId = null) => ({
  id, customerId: 'c1', customerName: '客戶甲', date, status,
  slots: [{ entitlementId: 'ent-followup', courseId: 'course-followup', status, followupForVisitId: examId }],
});
const task = (over = {}) => ({
  customerId: 'c1', customerName: '客戶甲', done: false, autoGenerated: true, dueDate: '2026-09-01', ...over,
});
const reportTicked = (visitId) => task({
  id: `r-${visitId}`, visitId, kind: REPORT_TASK_KIND, done: true, doneAt: '2026-09-05T02:00:00.000Z',
});

const sync = (o) => syncFollowupTasks({
  customer: CUSTOMER, entitlements: [checkup(), followup()], visits: [], tasks: [], coursesById: COURSES, ...o,
});
const grows = (o) => sync(o).create.map((t) => `${t.kind}@${t.visitId}`).sort();

const A = exam('vA', '2026-06-01');
const B = exam('vB', '2026-08-01');

describe('多出來那一次也追報告', () => {
  test('買 1 次、做了 2 次、二返做完 1 次（沒連結）→ 新的那一次（B）長報告；二返照位置配給最舊的（A），A 不多長', () => {
    assert.deepEqual(
      grows({ visits: [A, B, second('s1', '2026-06-20')] }),
      [`${REPORT_TASK_KIND}@vB`],
    );
  });

  test('二返有連結、做完了的那一次不長（照舊）', () => {
    assert.deepEqual(
      grows({ visits: [A, B, second('s1', '2026-08-20', 'done', 'vB')] }),
      [`${REPORT_TASK_KIND}@vA`],
    );
  });

  test('一場二返都沒買夠也沒做：兩次都追報告（以前只追得到一次）', () => {
    assert.deepEqual(grows({ visits: [A, B] }), [`${REPORT_TASK_KIND}@vA`, `${REPORT_TASK_KIND}@vB`]);
  });

  test('超出的那一次報告勾掉 → 長「寄報告給醫師」、**不長**「約二返」（沒有額度）', () => {
    const visits = [A, B, second('s1', '2026-06-20')];
    assert.deepEqual(grows({ visits, tasks: [reportTicked('vB')] }), [`${SEND_REPORT_TASK_KIND}@vB`]);
  });

  test('補一筆二返額度（次數 1 → 2）→ 那一次的「約二返」長出來（不用再存任何來訪）', () => {
    const visits = [A, B, second('s1', '2026-06-20')];
    const tasks = [reportTicked('vB'), task({ id: 'send-vB', visitId: 'vB', kind: SEND_REPORT_TASK_KIND })];
    assert.deepEqual(
      grows({ entitlements: [checkup(), followup({ totalQty: 2 })], visits, tasks }),
      [`${FOLLOWUP_TASK_KIND}@vB`],
    );
  });

  test('次數改回去（2 → 1）→ 那一張「約二返」收起來', () => {
    const visits = [A, B, second('s1', '2026-06-20')];
    const tasks = [reportTicked('vB'), task({ id: 'book-vB', visitId: 'vB', kind: FOLLOWUP_TASK_KIND })];
    const plan = sync({ visits, tasks });
    assert.deepEqual(plan.remove.map((r) => r.id), ['book-vB']);
    // 理由要是真的：不是「二返已經約好了」，是額度不夠（確認框照這一句講）
    assert.match(plan.remove[0].reason, /次數/);
    assert.doesNotMatch(plan.remove[0].reason, /約好了/);
  });

  test('二返真的約好了（有連結）才講「已經約好了」', () => {
    const visits = [A, B, second('s1', '2026-06-20'), second('s2', '2026-09-20', 'confirmed', 'vB')];
    const tasks = [reportTicked('vB'), task({ id: 'book-vB', visitId: 'vB', kind: FOLLOWUP_TASK_KIND })];
    const plan = sync({ entitlements: [checkup(), followup({ totalQty: 2 })], visits, tasks });
    assert.deepEqual(plan.remove.map((r) => r.reason), ['二返已經約好了']);
  });
});

describe('匯進來的舊健檢不補報告', () => {
  const imported = (v) => ({ ...v, importedFrom: '舊表 2026-10-19' });

  test('超出二返額度的那一次、是匯進來的、從來沒有過任何一張鏈上待辦 → 不長', () => {
    assert.deepEqual(grows({ visits: [imported(A), imported(B), second('s1', '2026-06-20')] }), []);
  });

  test('在二返額度裡的那一次照舊長（ADR-0139：匯進來、二返還沒做的那一次照樣追）', () => {
    assert.deepEqual(
      grows({ entitlements: [checkup({ totalQty: 2 }), followup({ totalQty: 2 })], visits: [imported(A), imported(B), second('s1', '2026-06-20')] }),
      [`${REPORT_TASK_KIND}@vB`],
    );
  });

  test('在 app 裡做完的超出那一次照樣長（不是匯進來的）', () => {
    assert.deepEqual(grows({ visits: [imported(A), B, second('s1', '2026-06-20')] }), [`${REPORT_TASK_KIND}@vB`]);
  });

  test('匯進來的、但這一次有過鏈上待辦（勾過又清掉的也算）→ 照常走', () => {
    const cleared = { ...reportTicked('vB'), deletedAt: '2026-09-10' };
    assert.deepEqual(
      grows({ visits: [imported(A), imported(B), second('s1', '2026-06-20')], tasks: [cleared] }),
      [`${SEND_REPORT_TASK_KIND}@vB`],
    );
  });
});

describe('確認框的句子（ADR-0070：拿寫入那一支的試算講）', () => {
  test('一位：每一張講是哪一天那一次健檢的', () => {
    const plan = sync({ visits: [A, B] });
    const lines = chainPlanLines(plan, [A, B], []);
    assert.equal(lines.length, 2);
    assert.match(lines.join('\n'), /待辦會多一張「追蹤健檢報告」/);
    assert.match(lines.join('\n'), /6\/1/);
  });

  test('收起來的那一張也講', () => {
    const visits = [A, B, second('s1', '2026-06-20')];
    const tasks = [reportTicked('vB'), task({ id: 'book-vB', visitId: 'vB', kind: FOLLOWUP_TASK_KIND })];
    const lines = chainPlanLines(sync({ visits, tasks }), visits, tasks);
    assert.match(lines.join('\n'), /「約二返」會收起來/);
  });

  test('好幾位（資料健檢一次補好幾筆）：照種類數', () => {
    const plans = [sync({ visits: [A, B] }), sync({ visits: [A] })];
    assert.deepEqual(chainCountLines(plans), ['待辦會多 3 張「追蹤健檢報告」']);
    assert.deepEqual(chainCountLines([]), []);
  });
});

describe('原始碼：改到健檢或二返額度的每一條路都重算', () => {
  const read = (rel) => readFileSync(fromRoot(rel), 'utf8').replace(/\r\n/g, '\n');
  const customers = read('public/js/data/customers.js');

  for (const name of ['createEntitlement', 'addEntitlements', 'updateEntitlement', 'updateEntitlements', 'removeEntitlement', 'restoreEntitlement']) {
    test(`data/customers.js 的 ${name}()`, () => {
      const start = customers.search(new RegExp(`export (?:async )?function ${name}\\(`));
      assert.ok(start >= 0, `${name} 要是一支 function（不是一行箭頭）`);
      const body = customers.slice(start, customers.indexOf('\n}\n', start));
      // 每一支都把那一份 plan 回給 toast 講（issue 17、19），所以拿的是整條鏈（`chainOf()`），不只 ops
      assert.match(body, /chainOf\(/);
    });
  }

  test('那一支小幫手真的叫寫入那一支（chainAfterEntitlements()）', () => {
    const start = customers.indexOf('const chainOf = ');
    assert.ok(start >= 0);
    assert.match(customers.slice(start, customers.indexOf('\n', start)), /chainAfterEntitlements\(/);
  });

  test('資料健檢的「補上二返額度」（不經過 entitlementWrites()）', () => {
    const health = read('public/js/data/health.js');
    const start = health.indexOf('export async function applyFixes(');
    assert.match(health.slice(start, health.indexOf('\n}\n', start)), /chainAfterEntitlements\(/);
  });

  // 段四審查：沒傳名字的那幾條路（改次數、刪掉、還原、補一筆、資料健檢）以前拿最新那一筆來訪上的名字快照 ——
  // 客人改過名、最新那一筆是已經結案的過去來訪（`renameTargets()` 不換它）時，待辦上的新名字被改回舊的（CLAUDE.md「客戶改名」）
  test('重算那一串時待辦上的名字讀客戶本人，不讀來訪上的快照', () => {
    const visits = read('public/js/data/visits.js');
    const start = visits.indexOf('export async function chainAfterEntitlements(');
    const body = visits.slice(start, visits.indexOf('\n}\n', start));
    assert.match(body, /customersData\.get\(customerId\)/);
    assert.doesNotMatch(body, /visits\.find\(\(v\) => v\.customerName\)/);
  });

  test('客戶詳情「補一筆二返額度」那一道不再寫死「健檢標成已完成才會長出約二返」', () => {
    const src = read('public/js/ui/views/customerDetail.js');
    assert.doesNotMatch(src, /健檢標成已完成才會長出/);
    assert.match(src, /chainPlanLines\(/);
  });
});

// 段四審查：刪掉那一筆二返額度（配對沒了）—— 「健檢還是已完成的」以前只問配得到二返的健檢，
// 刪掉的那一刻開著的報告與寄報告一起被收掉、理由寫「那一筆健檢不是已完成了」（刪除確認框也照印），
// 「約二返」的理由寫「二返已經約好了」。報告不吃二返額度（ADR-0159 第一段），刪掉二返額度也一樣
describe('刪掉二返額度：報告與寄報告照留，約二返講真的理由', () => {
  const tasks = [
    task({ id: 'rep-A', visitId: 'vA', kind: REPORT_TASK_KIND }),
    reportTicked('vB'),
    task({ id: 'send-B', visitId: 'vB', kind: SEND_REPORT_TASK_KIND }),
    task({ id: 'book-B', visitId: 'vB', kind: FOLLOWUP_TASK_KIND }),
  ];
  const plan = sync({ entitlements: [checkup({ totalQty: 2 })], visits: [A, B], tasks });

  test('還沒勾的報告、寄報告不收', () => {
    const gone = plan.remove.map((r) => r.id);
    assert.ok(!gone.includes('rep-A'), '報告那一張不吃二返額度');
    assert.ok(!gone.includes('send-B'), '寄報告也不吃');
  });

  test('約二返收起來，理由是二返的次數不夠（不是「約好了」、不是「健檢不是已完成了」）', () => {
    const book = plan.remove.find((r) => r.id === 'book-B');
    assert.ok(book);
    assert.match(book.reason, /二返的次數不夠/);
  });
});
