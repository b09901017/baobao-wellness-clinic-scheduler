// 照片上已經放掉的段：「取消 Abovee」那一張一出生就勾好（abovee-status-follows-photo-2026-10-15/02）。
//
// 她 10/15：「然後就不用產生取消和重排的待辦 ? 對吧我都在abovee改好了，不用再叫我去取消和重排啊?」
//
// **不能只是「這一次不長」**：任務在每一次存那一天時重算（`syncTasksForVisit()` → `cancelTasksFor()`），
// 只要沒有一張「看過的」蓋住那一段，下一次存同一天就補長一張。所以長一張**已經勾掉的**（ADR-0106：勾過的才算做過）。
//
// 例子一律假名。

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

import { cancelTasksFor, syncTasksForVisit } from '../public/js/domain/taskRules.js';
import { cancelTaskLines, cancelConsequences } from '../public/js/domain/consequences.js';
import { describeParts } from '../public/js/domain/audit.js';
import { reviewOf } from '../public/js/domain/dayReview.js';

const TODAY = '2026-09-01';
const AT = '2026-09-01T03:00:00.000Z';

const COURSES = {
  // 壓在 Abovee、確認後什麼都不用掛（C 類那種）
  sis: { id: 'sis', name: 'SIS', systems: ['Abovee'] },
  // 壓在 Abovee、確認後掛 Examine（A 類那種）
  exam: { id: 'exam', name: '健檢', systems: ['Abovee', 'Examine'] },
  // 壓在 Examine（不是 Abovee）
  ex: { id: 'ex', name: '只在 Examine', systems: ['Examine'] },
  // 不用壓（ADR-0126）
  hrv: { id: 'hrv', name: 'HRV', systems: [] },
};

const slot = (courseId, startsAt, status = 'confirmed', over = {}) => ({ courseId, startsAt, endsAt: startsAt, status, ...over });
const visit = (slots, over = {}) => ({
  id: 'v1', customerId: 'c1', customerName: '客戶A', date: '2026-09-10', status: 'confirmed', slots, ...over,
});
const ids = (tasks) => tasks.map((t, i) => ({ id: `t${i}`, visitId: 'v1', ...t }));

describe('cancelTasksFor() 的 freed', () => {
  test('一段 Abovee 的課、照片上已經放掉 → 長一張已勾的「取消 Abovee」蓋住那一段', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00')]);
    const tasks = cancelTasksFor(v, [], COURSES, TODAY, { freed: [0], at: AT });
    assert.deepEqual(tasks.map((t) => [t.kind, t.done, t.doneAt, t.slotIndexes]), [['取消 Abovee', true, AT, [0]]]);
    // 那一句不叫她回去放（她已經放掉了）
    assert.doesNotMatch(tasks[0].note, /回去/);
  });

  test('freed 指到一段還活著的：什麼都不長（只有取消掉的段才有東西要收）', () => {
    const v = visit([slot('sis', '10:00'), slot('sis', '14:00')]);
    assert.deepEqual(cancelTasksFor(v, [], COURSES, TODAY, { freed: [1], at: AT }), []);
  });

  test('那一段在 Examine 掛過（那張掛號勾掉了）→ Examine 那一張照長、沒勾', () => {
    const v = visit([slot('exam', '10:00', 'cancelled')]);
    const registered = { id: 'r1', visitId: 'v1', kind: 'Examine', done: true, autoGenerated: true, slotIndexes: [0] };
    const tasks = cancelTasksFor(v, [registered], COURSES, TODAY, { freed: [0], at: AT });
    assert.deepEqual(tasks.map((t) => [t.kind, t.done]), [['取消 Abovee', true], ['取消 Examine', false]]);
  });

  test('那門課壓在 Examine、freed 有它 → 照長、沒勾（照片只證明 Abovee 上那一格）', () => {
    const v = visit([slot('ex', '10:00', 'cancelled'), slot('sis', '14:00')]);
    const tasks = cancelTasksFor(v, [], COURSES, TODAY, { freed: [0], at: AT });
    assert.deepEqual(tasks.map((t) => [t.kind, t.done]), [['取消 Examine', false]]);
  });

  test('拆張：A 段照片上放掉了、B 段之前取消而它的「取消 Abovee」被復原過 → 兩張，A 的已勾、B 的沒勾', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00', 'cancelled'), slot('sis', '16:00')]);
    // 復原：軟刪除、沒勾過 → `seenTasks()` 不算它
    const undone = { id: 'u1', visitId: 'v1', kind: '取消 Abovee', done: false, deletedAt: 'x', autoGenerated: true, slotIndexes: [1] };
    const tasks = cancelTasksFor(v, [undone], COURSES, TODAY, { freed: [0], at: AT });
    const byDone = Object.fromEntries(tasks.map((t) => [String(t.done), t.slotIndexes]));
    assert.equal(tasks.length, 2);
    assert.deepEqual(byDone, { true: [0], false: [1] });
    assert.ok(tasks.every((t) => t.kind === '取消 Abovee'));
  });

  test('整天取消也一樣（兩段都在 freed）→ 一張已勾', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00', 'cancelled')], { status: 'cancelled' });
    const tasks = cancelTasksFor(v, [], COURSES, TODAY, { freed: [0, 1], at: AT });
    assert.deepEqual(tasks.map((t) => [t.kind, t.done, t.slotIndexes]), [['取消 Abovee', true, [0, 1]]]);
  });

  test('不用壓的課（HRV）：一張都不長', () => {
    const v = visit([slot('hrv', '10:00', 'cancelled'), slot('sis', '14:00')]);
    assert.deepEqual(cancelTasksFor(v, [], COURSES, TODAY, { freed: [0], at: AT }), []);
  });

  test('不帶 freed：跟以前一模一樣（沒勾）', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00')]);
    assert.deepEqual(cancelTasksFor(v, [], COURSES, TODAY).map((t) => [t.kind, t.done, t.doneAt]), [['取消 Abovee', false, null]]);
  });
});

describe('存兩次那一天（syncTasksForVisit()）', () => {
  const ctx = { coursesById: COURSES, today: TODAY };

  test('只取消一段那一條路：第一次帶 freed 長已勾的；再存一次（改另一段的治療師、不帶 freed）不多長', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00')]);
    const first = syncTasksForVisit(v, [], { ...ctx, freed: [0], at: AT });
    assert.deepEqual(first.create.map((t) => [t.kind, t.done]), [['取消 Abovee', true]]);

    const again = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00', 'confirmed', { therapistId: 's2' })]);
    const second = syncTasksForVisit(again, ids(first.create), ctx);
    assert.deepEqual(second.create, []);
    assert.deepEqual(second.remove, [], '已勾的那一張不會被收掉');
  });

  test('整天取消那一條路也帶得到 freed', () => {
    const v = visit([slot('sis', '10:00', 'cancelled')], { status: 'cancelled' });
    const { create } = syncTasksForVisit(v, [], { ...ctx, freed: [0], at: AT });
    assert.deepEqual(create.map((t) => [t.kind, t.done]), [['取消 Abovee', true]]);
    assert.deepEqual(syncTasksForVisit(v, ids(create), ctx).create, []);
  });

  test('之後在日曆上取消同一天另一段：照常長一張沒勾的、只蓋那一段', () => {
    const v = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00')]);
    const born = ids(syncTasksForVisit(v, [], { ...ctx, freed: [0], at: AT }).create);
    const later = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00', 'cancelled')]);
    const { create } = syncTasksForVisit(later, born, ctx);
    assert.deepEqual(create.map((t) => [t.kind, t.done, t.slotIndexes]), [['取消 Abovee', false, [1]]]);
  });
});

describe('確認框那一句（cancelTaskLines()）收同一個 freed', () => {
  test('帶 freed：不講「會多一張取消 Abovee」', () => {
    const after = visit([slot('sis', '10:00', 'cancelled'), slot('sis', '14:00')]);
    assert.deepEqual(cancelTaskLines(after, [], COURSES), ['待辦會多一張「取消 Abovee」—— 回去把那個時段放掉']);
    assert.deepEqual(cancelTaskLines(after, [], COURSES, { freed: [0] }), []);
  });

  test('Examine 掛過的照講', () => {
    const after = visit([slot('exam', '10:00', 'cancelled')]);
    const registered = { id: 'r1', visitId: 'v1', kind: 'Examine', done: true, autoGenerated: true, slotIndexes: [0] };
    assert.deepEqual(cancelTaskLines(after, [registered], COURSES, { freed: [0] }),
      ['待辦會多一張「取消 Examine」—— 回去把那一段的登記取消掉']);
  });

  test('不帶 freed 的取消確認框一個字都不變', () => {
    const v = visit([slot('sis', '10:00'), slot('sis', '14:00')]);
    const lines = cancelConsequences({ visit: v, slotIndex: 0, tasks: [], coursesById: COURSES });
    assert.ok(lines.includes('待辦會多一張「取消 Abovee」—— 回去把那個時段放掉'));
  });
});

describe('一出生就勾好的那一張在稽核上長什麼樣（spec「我自己定」：接受）', () => {
  const [task] = cancelTasksFor(visit([slot('sis', '10:00', 'cancelled')], { status: 'cancelled' }), [], COURSES, TODAY, { freed: [0], at: AT });
  const event = { action: 'tasks.create', targetPath: 'tasks/t1', before: null, after: task };

  test('「勾掉 … 取消 Abovee」，不是怪句子', () => {
    const visitOf = (id) => (id === 'v1' ? { date: '2026-09-10', slots: [{ courseName: 'SIS' }] } : null);
    const parts = describeParts(event, { visitOf });
    assert.equal(parts.lead, '勾掉');
    assert.match(parts.text, /取消 Abovee/);
  });

  test('「今天做了什麼」落在 ④ 登記掛號（跟她自己勾的一樣）', () => {
    const review = reviewOf([{ ...event, at: 'T' }]);
    assert.deepEqual(review.groups.map((g) => g.stage.id), ['register']);
  });
});

describe('存檔那一支只負責把 freed 傳下去（data/visits.js）', () => {
  const src = readFileSync(new URL('../public/js/data/visits.js', import.meta.url), 'utf8');

  test('save() 收 freed、交給 taskOps()，taskOps() 交給 syncTasksForVisit()', () => {
    assert.match(src, /export async function save\(visit, customerVisits = \[\], \{ freed = \[\] \} = \{\}\)/);
    assert.match(src, /taskOps\(next, \{[^}]*freed[^}]*\}\)/);
    assert.match(src, /syncTasksForVisit\(visit, existing, \{[^}]*freed[^}]*\}\)/);
  });

  test('不在 taskOps() 事後把任務改成已勾（確認框算不到，ADR-0070）', () => {
    const at = src.indexOf('async function taskOps(');
    const body = src.slice(at, src.indexOf('\n}', at));
    assert.doesNotMatch(body, /done:\s*true/);
  });
});
