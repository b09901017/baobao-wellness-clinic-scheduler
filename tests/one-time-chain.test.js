describe('不變量：沒有一次性的段時原封不動', () => {
  test('同一個陣列、同一個物件交回去（一般客人算出來的每一格跟這一支之前一模一樣）', () => {
    const input = { entitlements: REAL_ENTS, visits: REAL_VISITS, coursesById };
    const out = withOneTimeChain(input);
    assert.equal(out.entitlements, REAL_ENTS);
    assert.equal(out.visits, REAL_VISITS);
  });

  test('空的、沒給也一樣', () => {
    const out = withOneTimeChain({});
    assert.deepEqual(out, { entitlements: [], visits: [] });
  });

  test('隨機的一般客人 500 組：每一組都是同一個陣列交回去', () => {
    // 週期 2^32 的亂數（docs/agents/lessons.md「查的方法」：不要用會掉精度的那一種）
    let seed = 20261105;
    const rand = (n) => { seed = (Math.imul(seed, 1103515245) + 12345) >>> 0; return seed % n; };
    const statuses = ['pending_confirm', 'confirmed', 'done', 'no_show', 'cancelled'];
    const shapes = [
      () => ({ entitlementId: 'ent-exam', courseId: 'course-checkup' }),
      () => ({ entitlementId: 'ent-2nd', courseId: 'course-followup', followupForVisitId: `r${rand(6)}` }),
      () => ({ entitlementId: null, courseId: 'course-followup', followupNth: 3 + rand(3), followupForVisitId: `r${rand(6)}` }),
      () => ({ entitlementId: null, courseId: 'course-followup', examNotMine: true }),
      () => ({ entitlementId: null, courseId: 'course-fm', giftKind: rand(2) ? 'trial' : 'gift' }),
      () => ({ entitlementId: null, courseId: 'course-followup' }),
      () => ({ entitlementId: 'ent-sis', courseId: 'course-recovery', oneTime: 'true' }),
    ];
    for (let k = 0; k < 500; k += 1) {
      const visits = Array.from({ length: 1 + rand(6) }, (_, i) => {
        const status = statuses[rand(statuses.length)];
        return { id: `r${i}`, date: `2026-10-${String(1 + i).padStart(2, '0')}`, status, slots: [plain({ ...shapes[rand(shapes.length)](), status })] };
      });
      const out = withOneTimeChain({ entitlements: REAL_ENTS, visits, coursesById });
      assert.equal(out.visits, visits, `第 ${k} 組`);
      assert.equal(out.entitlements, REAL_ENTS, `第 ${k} 組`);
    }
  });
});

describe('投影：一對只在記憶體裡的額度', () => {
  const visits = [examVisit('v-e1', '2026-10-03'), secondVisit('v-2', '2026-11-10', 'v-e1')];

  test('一門健檢課程一對：健檢那一筆的總數＝還算數的一次性健檢段、二返那一筆指回去、同數', () => {
    const { entitlements } = withOneTimeChain({ visits, coursesById });
    assert.equal(entitlements.length, 2);
    const [exam, second] = entitlements;
    assert.ok(isOneTimeEntitlementId(exam.id) && isOneTimeEntitlementId(second.id));
    assert.equal(exam.courseId, 'course-checkup');
    assert.equal(exam.totalQty, 1);
    assert.equal(second.courseId, 'course-followup');
    assert.equal(second.followupForEntitlementId, exam.id);
    assert.equal(second.totalQty, 1);
    assert.ok(exam.label && second.label);
    // `pairsOf()` 照舊配得到（`counts()` 讀 `totalQty`）
    const [pair] = pairsOf(entitlements, coursesById);
    assert.equal(pair.followup.id, second.id);
  });

  test('只在抄出來的那一份填：健檢段 → 健檢那一筆、接在一次性健檢上的二返 → 二返那一筆；原本那一份一格都沒動', () => {
    const before = JSON.stringify(visits);
    const out = withOneTimeChain({ visits, coursesById });
    assert.equal(out.visits[0].slots[0].entitlementId, out.entitlements[0].id);
    assert.equal(out.visits[1].slots[0].entitlementId, out.entitlements[1].id);
    assert.equal(JSON.stringify(visits), before);
    assert.equal(visits[0].slots[0].entitlementId, null);
  });

  test('n返、健檢不是我排的、一般的段不填', () => {
    const list = [
      examVisit('v-e1', '2026-10-03'),
      nthVisit('v-3', '2026-11-20', 'v-e1', 3),
      { ...secondVisit('v-n', '2026-11-21', null), slots: [ot({ courseId: 'course-followup', examNotMine: true })] },
      { id: 'v-x', date: '2026-11-22', status: 'pending_confirm', slots: [plain({ entitlementId: null, courseId: 'course-fm', giftKind: 'trial' })] },
    ];
    const out = withOneTimeChain({ visits: list, coursesById });
    assert.equal(out.visits[1].slots[0].entitlementId, null);
    assert.equal(out.visits[2].slots[0].entitlementId, null);
    assert.equal(out.visits[3], list[3]);
  });

  test('取消的健檢不算進總數，但那一對照樣在（接著它的二返要認得出來）', () => {
    const out = withOneTimeChain({ visits: [examVisit('v-e1', '2026-10-03', 'cancelled')], coursesById });
    assert.equal(out.entitlements[0].totalQty, 0);
    assert.equal(out.visits[0].slots[0].entitlementId, out.entitlements[0].id);
  });

  test('冪等：投影兩次跟一次一樣（轉成客戶、帶著真的額度也是）', () => {
    const list = [...visits, nthVisit('v-3', '2026-11-20', 'v-e1'), ...REAL_VISITS];
    const once = withOneTimeChain({ entitlements: REAL_ENTS, visits: list, coursesById });
    const twice = withOneTimeChain({ ...once, coursesById });
    assert.deepEqual(twice, once);
    // 投影過的那幾筆再投影一次，連物件都不換
    assert.ok(twice.visits.every((v, i) => v === once.visits[i]));
  });

  test('一次性的段後來都沒了：那一對也拿掉', () => {
    const once = withOneTimeChain({ visits, coursesById });
    const out = withOneTimeChain({ entitlements: once.entitlements, visits: REAL_VISITS, coursesById });
    assert.deepEqual(out.entitlements, []);
  });

  test('counts() 拿真的額度算，一次性的段一次都不算（拿那一對算才算）', () => {
    const out = withOneTimeChain({ entitlements: REAL_ENTS, visits: [...visits, ...REAL_VISITS], coursesById });
    assert.equal(counts(REAL_ENTS[0], out.visits, 'ent-exam').done, 1);
    assert.equal(counts(out.entitlements.at(-2), out.visits, out.entitlements.at(-2).id).done, 1);
  });

  test('originalOf：換回她資料裡的那一份（照位置，還沒有 id 的那一筆也換得回來）', () => {
    const draft = { ...examVisit(undefined, '2026-11-01'), id: undefined };
    const list = [...visits, draft];
    const out = withOneTimeChain({ visits: list, coursesById });
    const back = originalOf(list, out.visits);
    assert.equal(back.visit(out.visits[2]), draft);
    assert.equal(back.slot(out.visits[1], out.visits[1].slots[0]), visits[1].slots[0]);
    assert.equal(back.visit(null), null);
  });
});

