// 一次性客人的健檢那一串（2026-11-05，ADR-0172 決定三，`.scratch/one-time-guests/issues/02`）。
//
// 一次性客人沒有額度，健檢那一串（以額度為軸）一張都不會長。算的時候替他生一對只在記憶體裡的額度
// （`domain/oneTimeChain.js` 的 `withOneTimeChain()`），鏈的規則一個字都不改。她：
//
// > 他之前有用卷換了健檢，所以我要幫她排二返，雖然這次失約，但是之後還是會幫他排……
// > 約完二返後的寫紀錄等等待辦，我也還是都要做，就和一般來訪一樣
//
// 這一支一半在釘「跟一般客人一模一樣」，另一半在釘**一般客人一個字都沒變**（沒有一次性的段時原封不動）
// 與**那一對的 id 一個都不會跑出去**（任務、存檔、回給呼叫端的來訪）。

