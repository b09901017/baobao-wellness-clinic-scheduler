describe('轉成我的客戶之後：真的那一對與那一對各算各的', () => {
  // 一次性的時候做了健檢（v-e1）、二返做完了；轉成客戶之後買了真的健檢＋二返，真的健檢也做完了（r1）
  const ents = REAL_ENTS.map((e) => (e.id === 'ent-exam' || e.id === 'ent-2nd' ? { ...e, totalQty: 1 } : e));
  const realExam = { id: 'r1', customerId: 'g1', date: '2026-11-01', status: 'done', slots: [plain({ entitlementId: 'ent-exam', status: 'done', attended: true })] };

  test('一次性的二返不會被配給真的健檢（真的那一次照樣長報告）', () => {
    const visits = [examVisit('v-e1', '2026-10-03'), secondVisit('v-2', '2026-10-20', 'v-e1', 'done'), realExam];
    assert.deepEqual(kinds(sync(visits, [], ents).create), [`${REPORT_TASK_KIND}@r1`]);
  });

  test('真的二返沒連結、做完了：照位置配給真的健檢，不吃一次性的那一次', () => {
    const realSecond = { id: 'r2', customerId: 'g1', date: '2026-11-10', status: 'done', slots: [plain({ entitlementId: 'ent-2nd', courseId: 'course-followup', status: 'done', attended: true })] };
    const visits = [examVisit('v-e1', '2026-10-03'), realExam, realSecond];
    // 一次性那一次的報告照長（它的二返還沒做）；真的那一次被那一場沒連結的二返蓋掉
    assert.deepEqual(kinds(sync(visits, [], ents).create), [`${REPORT_TASK_KIND}@v-e1`]);
  });

  test('一次性的健檢還欠二返 → 「做什麼」那一排多一顆「二返（一次性那一次）」（排在二返那一組）', () => {
    const visits = [examVisit('v-e1', '2026-10-03'), realExam];
    const options = slotOptionsFor({ entitlements: ents, visits, courses: COURSES, equipment: SEED.equipment });
    const mine = options.find((o) => o.entitlementId === ONE_TIME_SECOND_PICK);
    assert.ok(mine, options.map((o) => o.label).join('、'));
    assert.equal(mine.isOneTimeSecond, true);
    assert.equal(mine.entitlement, null);
    assert.equal(mine.remaining, '—');
    assert.equal(mine.course.id, 'course-followup');
    assert.match(mine.label, /一次性那一次/);
    assert.equal(mine.group, '二返・n返');
  });

  test('那一場約了 → 那一顆收起來；沒來 → 又回來', () => {
    const booked = [examVisit('v-e1', '2026-10-03'), secondVisit('v-2', '2026-11-20', 'v-e1'), realExam];
    assert.ok(!slotOptionsFor({ entitlements: ents, visits: booked, courses: COURSES }).some((o) => o.isOneTimeSecond));
    const missed = [examVisit('v-e1', '2026-10-03'), secondVisit('v-2', '2026-11-20', 'v-e1', 'no_show'), realExam];
    assert.ok(slotOptionsFor({ entitlements: ents, visits: missed, courses: COURSES }).some((o) => o.isOneTimeSecond));
  });

  test('按了那一顆組出來的段：一次性、接那一次健檢、存得下去', () => {
    const visits = [examVisit('v-e1', '2026-10-03'), realExam];
    const choices = oneTimeExamChoices({ entitlements: ents, visits, coursesById, courseId: 'course-followup' });
    assert.deepEqual(choices.map((c) => [c.visitId, c.pickable]), [['v-e1', true]]);
    const { slot, errors } = slotFromPicks({
      oneTime: true, courseId: 'course-followup', followupForVisitId: choices[0].visitId, startsAt: '10:00',
    }, { courses: COURSES, equipment: SEED.equipment, entitlements: ents, visits });
    assert.deepEqual(errors, []);
    const draft = { customerId: 'g1', customerName: '客戶A', date: '2026-11-20', status: 'pending_confirm', slots: [slot] };
    const converted = { ...GUEST, oneTime: false };
    assert.deepEqual(validateVisit(draft, vctx({ customer: converted, entitlements: ents, customerVisits: visits })).errors, []);
  });

  test('「排多久」那一排不會把它換成體驗；一般客人沒有那一顆', () => {
    assert.equal(trialFromMinutes({ value: ONE_TIME_SECOND_PICK, course: coursesById['course-followup'], minutes: 30, courses: COURSES }), null);
    assert.ok(!slotOptionsFor({ entitlements: REAL_ENTS, visits: REAL_VISITS, courses: COURSES }).some((o) => o.isOneTimeSecond));
    assert.ok(arrangeSlotOptions([], COURSES).length === 0);
  });
});

