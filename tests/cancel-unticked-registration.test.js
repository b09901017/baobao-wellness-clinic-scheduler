// 取消時講出「還沒勾的 Examine／耀聖會被收掉」（abovee-status-follows-photo-2026-10-15/10）。
//
// 她 10/15 問：「如果我忘記勾掉 Examine／耀聖的預約待辦呢，會被當成沒做嗎？」—— 會。取消那一段時那一張被系統收掉，
// 也不長「取消 Examine」。她其實掛了只是忘了勾的話，沒有人提醒她回去收 —— 所以確認框要講，而且講下一步。
//
// 句子講的要跟真的寫下去的一樣（ADR-0070）：拿 `syncTasksForVisit()` 算。
//
// 例子一律假名。

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';

import { cancelConsequences, rebookConsequences, registrationDropLines } from '../public/js/domain/consequences.js';
import { syncTasksForVisit } from '../public/js/domain/taskRules.js';

const COURSES = {
  exam: { id: 'exam', name: '健檢', systems: ['Abovee', 'Examine'] },
  sis: { id: 'sis', name: 'SIS', systems: ['Abovee'] },
};
const slot = (courseId, startsAt, status = 'confirmed') => ({ courseId, startsAt, endsAt: startsAt, status });
const visit = (slots, over = {}) => ({
  id: 'v1', customerId: 'c1', customerName: '客戶A', date: '2026-09-10', status: 'confirmed', slots, ...over,
});
const examine = (over = {}) => ({ id: 't1', visitId: 'v1', kind: 'Examine', done: false, autoGenerated: true, slotIndexes: [0], ...over });

const NEXT = '已經在 Examine 掛了、只是還沒勾的話，先去待辦勾掉它 —— 這樣才會長「取消 Examine」提醒你回去收';
const said = (lines) => lines.filter((l) => /Examine|耀聖/.test(l));

describe('只取消幾段', () => {
  test('那一段的 Examine 沒勾 → 講會被收掉＋下一步', () => {
    const v = visit([slot('exam', '10:00'), slot('sis', '14:00')]);
    const lines = cancelConsequences({ visit: v, slotIndex: 0, tasks: [examine()], coursesById: COURSES });
    assert.deepEqual(said(lines), ['還沒勾的「Examine」會被收掉', NEXT]);
  });

  test('勾了：不講這兩句，照舊講「會多一張取消 Examine」', () => {
    const v = visit([slot('exam', '10:00'), slot('sis', '14:00')]);
    const lines = cancelConsequences({ visit: v, slotIndex: 0, tasks: [examine({ done: true })], coursesById: COURSES });
    assert.deepEqual(said(lines), ['待辦會多一張「取消 Examine」—— 回去把那一段的登記取消掉']);
  });

  test('一張 Examine 蓋兩段、取消其中一段 → 講會拿掉這一段＋下一步', () => {
    const v = visit([slot('exam', '10:00'), slot('exam', '14:00')]);
    const lines = cancelConsequences({ visit: v, slotIndex: 0, tasks: [examine({ slotIndexes: [0, 1] })], coursesById: COURSES });
    assert.deepEqual(said(lines), ['還沒勾的「Examine」會拿掉這一段（還在的段照舊）', NEXT]);
  });

  test('沒有 Examine 那一張：不講', () => {
    const v = visit([slot('exam', '10:00'), slot('sis', '14:00')]);
    assert.deepEqual(said(cancelConsequences({ visit: v, slotIndex: 0, tasks: [], coursesById: COURSES })), []);
  });

  test('Examine 與耀聖都沒勾：一句講兩個，下一步也講兩個', () => {
    const courses = { ...COURSES, exam: { ...COURSES.exam, systems: ['Abovee', 'Examine', '耀聖'] } };
    const v = visit([slot('exam', '10:00'), slot('sis', '14:00')]);
    const tasks = [examine(), examine({ id: 't2', kind: '耀聖' })];
    assert.deepEqual(said(cancelConsequences({ visit: v, slotIndex: 0, tasks, coursesById: courses })), [
      '還沒勾的「Examine」、「耀聖」會被收掉',
      '已經在 Examine、耀聖 掛了、只是還沒勾的話，先去待辦勾掉 —— 這樣才會長「取消 Examine」、「取消 耀聖」提醒你回去收',
    ]);
  });
});

describe('整天取消', () => {
  test('原本那一句照講，多一句下一步', () => {
    const v = visit([slot('exam', '10:00')]);
    const lines = cancelConsequences({ visit: v, tasks: [examine()], coursesById: COURSES });
    assert.deepEqual(said(lines), ['還沒做完的「Examine」會被收掉', NEXT]);
  });

  test('只有「寫紀錄」要收：不講下一步', () => {
    const v = visit([slot('exam', '10:00')]);
    const record = { id: 'r1', visitId: 'v1', kind: '寫紀錄', done: false, autoGenerated: true, slotIndexes: [0] };
    const lines = cancelConsequences({ visit: v, tasks: [record], coursesById: COURSES });
    assert.ok(lines.includes('還沒做完的「寫紀錄」會被收掉'));
    assert.ok(!lines.some((l) => /先去待辦勾掉/.test(l)));
  });
});

describe('批次取消：任務是好幾天攤成一份的', () => {
  const A = visit([slot('exam', '10:00')], { id: 'vA' });
  const B = visit([slot('exam', '10:00')], { id: 'vB', date: '2026-09-11' });

  test('A 那一天勾掉的 Examine 不會讓 B 講「會多一張取消 Examine」', () => {
    const tasks = [examine({ id: 'tA', visitId: 'vA', done: true })];
    const lines = cancelConsequences({ visit: B, slotIndex: [0], tasks, coursesById: COURSES });
    assert.deepEqual(said(lines), []);
  });

  test('A 那一天沒勾的 Examine 不會讓 B 講「會被收掉」', () => {
    const tasks = [examine({ id: 'tA', visitId: 'vA' })];
    const lines = cancelConsequences({ visit: B, slotIndex: [0], tasks, coursesById: COURSES });
    assert.deepEqual(said(lines), []);
  });

  test('B 自己的照講', () => {
    const tasks = [examine({ id: 'tA', visitId: 'vA', done: true }), examine({ id: 'tB', visitId: 'vB' })];
    const lines = cancelConsequences({ visit: B, slotIndex: [0], tasks, coursesById: COURSES });
    assert.deepEqual(said(lines), ['還沒勾的「Examine」會被收掉', NEXT]);
  });
});

describe('講的跟真的寫下去的一樣', () => {
  test('registrationDropLines() 跟 syncTasksForVisit() 收掉的是同一張', () => {
    const after = visit([slot('exam', '10:00', 'cancelled'), slot('sis', '14:00')]);
    const tasks = [examine()];
    const { remove } = syncTasksForVisit(after, tasks, { coursesById: COURSES });
    assert.deepEqual(remove.map((r) => r.id), ['t1']);
    assert.deepEqual(registrationDropLines(after, tasks, COURSES), ['還沒勾的「Examine」會被收掉', NEXT]);
  });

  test('改期（rebookSlot 那一種：舊的取消）照樣講得出來 —— 句子不綁在 cancelConsequences 裡', () => {
    const after = visit([slot('exam', '10:00', 'cancelled'), slot('exam', '11:00', 'pending_confirm')]);
    assert.deepEqual(registrationDropLines(after, [examine()], COURSES), ['還沒勾的「Examine」會被收掉', NEXT]);
  });

  test('日曆「改這一段」改了時間（舊的取消、新的接在尾巴）那一道也講', () => {
    const before = visit([slot('exam', '10:00')]);
    const after = visit([slot('exam', '10:00', 'cancelled'), slot('exam', '11:00', 'pending_confirm')]);
    const { lines } = rebookConsequences({ before, after, index: 0, tasks: [examine()], coursesById: COURSES });
    assert.ok(lines.includes('還沒勾的「Examine」會被收掉'), lines.join(' / '));
    assert.ok(lines.includes(NEXT));
  });
});
