// 任務的存取。
//
// 任務幾乎都不是手動建立的，而是來訪存檔時連帶產生的 —— 那段在 data/visits.js，
// 跟來訪本身寫在同一個 batch 裡，不會出現「來訪存進去了但任務沒產生」。
// 這裡只負責讀，以及她在待辦中心勾完成。

import { where } from 'https://www.gstatic.com/firebasejs/11.0.2/firebase-firestore.js';

import * as repo from './repo.js';
import { followupOpsAfterTaskChange } from './visits.js';

const PATH = 'tasks';

export const get = (id) => repo.getOne(PATH, id);

/**
 * 還沒做完的任務，死線近的在前。待辦中心的主清單。
 * 需要 (deletedAt, done, dueDate asc) 複合索引，已列在 firestore.indexes.json。
 */
export function listOpen() {
  return repo.list(PATH, {
    wheres: [where('done', '==', false)],
    order: ['dueDate', 'asc'],
  });
}

/**
 * 已經勾掉的任務，完成日期新的在前。待辦那幾頁的「已完成」那一格用。
 *
 * **有上限。** 她要看的是「最近做完的」，不是全部歷史 —— 一年之後這個集合
 * 有好幾千筆，而那一格只是讓她確認「我剛剛勾掉的那幾筆去哪了」與勾錯了點得回來。
 * 報表要的那一組走 `listForReport()`。
 *
 * 需要 (deletedAt, done, doneAt desc) 複合索引，已列在 firestore.indexes.json。
 */
export function listDone(limit = 200) {
  return repo.list(PATH, {
    wheres: [where('done', '==', true)],
    order: ['doneAt', 'desc'],
    limit,
  });
}

/** 某一筆來訪的任務，含已完成的。來訪存檔時要拿它來比對。 */
export function listByVisit(visitId) {
  return repo.list(PATH, { wheres: [where('visitId', '==', visitId)] });
}

/**
 * 某一筆來訪的任務，**連軟刪除的一起**。來訪存檔時拿來比對的那一份。
 *
 * ## 為什麼比對要看得到被清掉的那幾張
 *
 * 「清掉這 N 筆」與已完成那一列的垃圾桶都是軟刪除（SPEC 第 6.1 節）。
 * 而 `syncTasksForVisit()` 問的是「這一件事**有沒有人做過**」——
 * 做過了就是做過了，那一列被清掉只代表她不想再看到它。
 *
 * 2026-09-16 之前比對走 `listByVisit()`，而 `repo.list()` 一律濾掉
 * `deletedAt` —— 於是清掉之後同一筆來訪再存一次，做過的那幾張會重新長出來：
 *
 *   取消一段 → 「取消 Abovee」勾掉 → 清掉 → 那一天結案 → **又一張，死線已經過了**
 *   A 類已確認 → Examine、耀聖勾掉 → 清掉 → 改那一段的時間 → **又各一張**
 *
 * 而那幾張假的待辦會叫她**再去 Examine 掛一次號**，或回 Abovee 放掉一個
 * 可能已經被別人排進去的時段（報告 §2.2）。
 *
 * **只給比對用。** 待辦中心那幾頁照舊走 `listByVisit()` —— 她清掉的就是要消失。
 */
export function listByVisitForSync(visitId) {
  return repo.listWithDeleted(PATH, { wheres: [where('visitId', '==', visitId)] });
}

/** 某位客戶的全部任務。客戶詳情頁的任務歷史用。 */
export function listByCustomer(customerId) {
  return repo.list(PATH, { wheres: [where('customerId', '==', customerId)] });
}

/**
 * 報表要的那些任務。試算表報表與 `#/settings/report` 的 TODO / FINISHED 兩塊用。
 *
 * 不逐位客戶查：一次要畫二十幾位，那是二十幾次讀取。
 *
 * **兩邊不對稱，這是刻意的：**
 *
 * - **沒做完的全部拿。** 死線在一年前的逾期任務照樣要出現在 TODO 那一塊 ——
 *   拖最久的那幾筆正是她最需要看到的。這一半天生有界（她會把它們做掉）。
 * - **做完的只拿最近的。** 這一半永遠只增不減，一年就好幾千筆。
 *
 * 以前這裡是 `repo.list(PATH, {})`，也就是**開站到今天的全部任務、沒有上限**，
 * 而試算表同步是每次寫入後十秒推一次（`data/sheetSync.js`）——
 * 那是整個 app 唯一一個又高頻又無上界的讀取，會逐年線性變貴。
 * 同一支檔案的 `listDone()` 早就想過這件事了（見它的註解），只有這裡漏掉。
 *
 * 兩個查詢吃的都是已經存在的複合索引，不必為這件事多開一個。
 *
 * @param {{doneLimit?: number}} [o] 做完的最多拿幾筆。500 筆 ÷ 二十幾位客戶
 *   ≈ 每人二十幾筆，比她的舊試算表一張分頁放得下的還多。
 */
export async function listForReport({ doneLimit = 500 } = {}) {
  const [open, done] = await Promise.all([listOpen(), listDone(doneLimit)]);
  return [...open, ...done];
}

export async function listDeleted() {
  return (await repo.listWithDeleted(PATH)).filter((t) => t.deletedAt);
}

/** 手動加的待辦，沒有掛在任何來訪底下。 */
export const create = (data) =>
  repo.create(PATH, { visitId: null, done: false, doneAt: null, autoGenerated: false, ...data });

export const update = (id, changes) => repo.update(PATH, id, changes);
export const remove = (id, reason) => repo.softDelete(PATH, id, reason);
export const restore = (id) => repo.restore(PATH, id);

/**
 * 勾完成／取消勾。一次可以勾很多筆 —— 她一天壓十幾個人，
 * 到 Examine 一次把整批掛完，回來要能一次勾掉（SPEC 第 8.1 節）。
 *
 * 一批寫在同一個 commit 裡，所以復原是把整批一起退回去，不是退一筆。
 *
 * **收的是任務本身不是 id。** 勾掉「追蹤健檢報告」要連著把「約二返」長出來
 *（ADR-0042 的鏈條），而那要知道勾的是哪一種、掛在哪位客戶身上。
 * 只收 id 的話這一層得先把那幾筆讀回來，而呼叫端手上本來就有 ——
 * 那是白白多一輪往返，她常常在大樓裡用行動網路（SPEC 第 6.9 節）。
 *
 * 鏈條那幾筆操作跟勾選**寫在同一個 commit**：不會出現「勾好了但約二返
 * 沒長出來」的半套狀態，而且復原退得回整組（`repo.withUndo` 只有剛好
 * 一次 commit 的動作給得出復原）。
 *
 * @param {object|object[]} tasks 要勾的那幾筆（要有 id、kind、customerId）
 * @param {boolean} done
 */
export async function setDone(tasks, done) {
  const rows = (Array.isArray(tasks) ? tasks : [tasks]).filter(Boolean);
  const doneAt = done ? new Date().toISOString() : null;
  const after = rows.map((t) => ({ ...t, done, doneAt }));

  return repo.commit([
    ...rows.map((t) => ({ op: 'update', path: PATH, id: t.id, changes: { done, doneAt } })),
    ...(await followupOpsAfterTaskChange(after)),
  ]);
}
