// 任務的存取。
//
// 任務幾乎都不是手動建立的，而是來訪存檔時連帶產生的 —— 那段在 data/visits.js，
// 跟來訪本身寫在同一個 batch 裡，不會出現「來訪存進去了但任務沒產生」。
// 這裡只負責讀，以及她在待辦中心勾完成。

import { where } from 'https://www.gstatic.com/firebasejs/11.0.2/firebase-firestore.js';

import * as repo from './repo.js';

const PATH = 'tasks';

export const get = (id) => repo.getOne(PATH, id);

/**
 * 還沒做完的任務，死線近的在前。待辦中心的主清單。
 * 需要 (deletedAt, done, dueDate asc) 複合索引，已列在 firestore.indexes.json。
 */
export function listOpen() {
  return repo.list(PATH, {
    wheres: [where('done', '==', false)],
    order: ['dueDate', 'asc'],
  });
}

/** 某一筆來訪的任務，含已完成的。來訪存檔時要拿它來比對。 */
export function listByVisit(visitId) {
  return repo.list(PATH, { wheres: [where('visitId', '==', visitId)] });
}

/** 某位客戶的全部任務。客戶詳情頁的任務歷史用。 */
export function listByCustomer(customerId) {
  return repo.list(PATH, { wheres: [where('customerId', '==', customerId)] });
}

/**
 * 全部任務，含已完成的。試算表報表的 TODO / FINISHED 兩塊用。
 *
 * 不逐位客戶查：一次要畫二十幾位，那是二十幾次讀取，而報表本來就要全部。
 */
export function listAll() {
  return repo.list(PATH, {});
}

export async function listDeleted() {
  return (await repo.listWithDeleted(PATH)).filter((t) => t.deletedAt);
}

/** 手動加的待辦，沒有掛在任何來訪底下。 */
export const create = (data) =>
  repo.create(PATH, { visitId: null, done: false, doneAt: null, autoGenerated: false, ...data });

export const update = (id, changes) => repo.update(PATH, id, changes);
export const remove = (id, reason) => repo.softDelete(PATH, id, reason);
export const restore = (id) => repo.restore(PATH, id);

/**
 * 勾完成／取消勾。一次可以勾很多筆 —— 她一天壓十幾個人，
 * 到 Examine 一次把整批掛完，回來要能一次勾掉（SPEC 第 8.1 節）。
 *
 * 一批寫在同一個 commit 裡，所以復原是把整批一起退回去，不是退一筆。
 */
export function setDone(ids, done) {
  const doneAt = done ? new Date().toISOString() : null;
  return repo.commit(
    (Array.isArray(ids) ? ids : [ids]).map((id) => ({
      op: 'update',
      path: PATH,
      id,
      changes: { done, doneAt },
    })),
  );
}
