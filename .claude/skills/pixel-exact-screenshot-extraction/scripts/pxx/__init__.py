# pxx：把「重畫候選字串、跟截圖逐像素比對」這件事拆成幾個可以單獨呼叫的模組。
#   conf      這一批截圖的畫法（字型、字級、顏色……）與工作目錄
#   img       讀圖（BGR 陣列）
#   synth     叫 Chromium 重畫字串、取回像素小塊；全機共用的同時數上限在這裡
#   grid      把截圖切成 (列, 欄) 的格子
#   match     誤差怎麼算、校起始位置、窮舉候選
#   reader    不知道內容的格子：逐字讀
#   discover  一欄的完整流程：已知詞彙 → 逐字讀 → 新詞回頭套到所有圖
#   badges    用顏色分的東西（狀態徽章）
#   charset   候選字集
